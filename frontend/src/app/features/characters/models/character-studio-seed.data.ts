function makeAbilities(scores: readonly [number, number, number, number, number, number]): readonly AbilityScoreVm[] {
  const defs: readonly [AbilityScoreVm['code'], string][] = [
    ['STR', 'Strength'],
    ['DEX', 'Dexterity'],
    ['CON', 'Constitution'],
    ['INT', 'Intelligence'],
    ['WIS', 'Wisdom'],
    ['CHA', 'Charisma'],
  ];
  return defs.map(([code, label], idx) => ({
    code,
    label,
    score: scores[idx],
    modifier: Math.floor((scores[idx] - 10) / 2),
  }));
}

